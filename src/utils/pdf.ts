import { jsPDF } from 'jspdf';

/**
 * Renders a simple labeled-row document and triggers a PDF download.
 * Kept deliberately plain (no layout library) since these are receipts/certificates,
 * not design-heavy documents.
 */
function renderSimpleDocument(title: string, rows: [string, string][], filename: string, footer?: string) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const marginX = 48;
  let y = 64;

  doc.setFontSize(18);
  doc.text(title, marginX, y);
  y += 32;

  doc.setFontSize(11);
  rows.forEach(([label, value]) => {
    doc.setFont('helvetica', 'bold');
    doc.text(label, marginX, y);
    doc.setFont('helvetica', 'normal');
    doc.text(String(value), marginX + 180, y);
    y += 22;
  });

  if (footer) {
    y += 20;
    doc.setFontSize(9);
    doc.setTextColor(120);
    doc.text(footer, marginX, y, { maxWidth: 480 });
  }

  doc.save(filename);
}

export interface ReceiptPdfData {
  amountPaid: string;
  transactionId: string;
  date: string;
  paymentMethod?: string;
}

export function downloadReceiptPdf(data: ReceiptPdfData) {
  renderSimpleDocument(
    'WazobiaTax Payment Receipt',
    [
      ['Amount Paid', data.amountPaid],
      ['Transaction ID', data.transactionId],
      ['Date', data.date],
      ...(data.paymentMethod ? [['Payment Method', data.paymentMethod] as [string, string]] : []),
    ],
    `wazobiatax-receipt-${data.transactionId}.pdf`,
    'This receipt was generated by the WazobiaTax app.'
  );
}

export interface CertificatePdfData {
  name: string;
  business: string;
  issueDate: string;
  expiryDate: string;
}

export function downloadCertificatePdf(data: CertificatePdfData) {
  renderSimpleDocument(
    'Tax Clearance Certificate',
    [
      ['Name', data.name],
      ['Business', data.business],
      ['Issue Date', data.issueDate],
      ['Expiry Date', data.expiryDate],
    ],
    `wazobiatax-tax-clearance-certificate.pdf`,
    'This certificate was generated by the WazobiaTax app and is valid for 12 months from the issue date.'
  );
}
